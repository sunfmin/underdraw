//! The view model and its conditions as one source file in the platform's
//! language: the types an implementation decodes fixtures and API data into,
//! and each named condition as a property (or function) of the root model,
//! so the real UI decides exactly what the description decides.

use underdraw_format::{Atom, Base, Definition, Expr, Field, Model, Op, Schema, Shape};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language {
    TypeScript,
    Swift,
    Kotlin,
}

impl Language {
    pub fn named(name: &str) -> Option<Language> {
        match name {
            "typescript" => Some(Language::TypeScript),
            "swift" => Some(Language::Swift),
            "kotlin" => Some(Language::Kotlin),
            _ => None,
        }
    }

    /// The file the code is meant to be saved as.
    pub fn file(self, root: &str) -> String {
        match self {
            Language::TypeScript => format!("{root}.ts"),
            Language::Swift => format!("{root}.swift"),
            Language::Kotlin => format!("{root}.kt"),
        }
    }
}

/// The name of the root type: the screen's name and `Model`.
pub fn root_name(model: &Model) -> String {
    format!("{}Model", model.screen())
}

/// The whole file: a header, the root type, each named type, then the
/// conditions.
pub fn file(model: &Model, language: Language) -> String {
    let root = root_name(model);
    let mut out = String::new();
    out.push_str(&header(model.screen(), language));
    out.push_str(&object(language, &root, &model.schema.roots()));
    let mut money = false;
    for (name, shape) in model.schema.types() {
        match shape {
            Shape::Object(fields) => {
                out.push('\n');
                out.push_str(&object(language, name, fields));
                money = money || uses_money(fields);
            }
            Shape::Enum(members) => {
                out.push('\n');
                out.push_str(&enumeration(language, name, members));
            }
        }
    }
    if money || uses_money(&model.schema.roots()) {
        out.push('\n');
        out.push_str(money_type(language));
    }
    if !model.conditions().is_empty() {
        out.push('\n');
        out.push_str(&conditions(model, language, &root));
    }
    out
}

fn header(screen: &str, language: Language) -> String {
    let lines = [
        format!("{screen}'s view model and conditions, generated by `underdraw handoff`."),
        "Regenerate it when the description changes; do not edit it.".to_string(),
        match language {
            Language::TypeScript => "Dates are ISO strings (2026-11-12): they compare as text.".to_string(),
            Language::Swift => {
                "Dates are ISO days (2026-11-12): decode with dateDecodingStrategy .formatted(yyyy-MM-dd)."
                    .to_string()
            }
            Language::Kotlin => "Uses kotlinx.serialization and kotlinx.datetime.".to_string(),
        },
    ];
    let mut out = String::new();
    for line in lines {
        out.push_str("// ");
        out.push_str(&line);
        out.push('\n');
    }
    match language {
        Language::TypeScript => {}
        Language::Swift => out.push_str("\nimport Foundation\n"),
        Language::Kotlin => {
            // A path through a parent already tested for null keeps its `?.`,
            // which Kotlin warns of; generated code must build warning-free.
            out.push_str("\n@file:Suppress(\"UNNECESSARY_SAFE_CALL\")\n");
            out.push_str("\nimport kotlinx.datetime.LocalDate\nimport kotlinx.serialization.Serializable\n")
        }
    }
    out.push('\n');
    out
}

fn uses_money(fields: &[(String, Field)]) -> bool {
    let mut found = false;
    for (_, field) in fields {
        found = found || field.base == Base::Money;
    }
    found
}

fn money_type(language: Language) -> &'static str {
    match language {
        Language::TypeScript => {
            "export interface Money {\n  amount: number;\n  /** ISO 4217, such as JPY */\n  currency: string;\n}\n"
        }
        Language::Swift => {
            "struct Money: Codable, Equatable {\n    var amount: Decimal\n    /// ISO 4217, such as JPY\n    var currency: String\n}\n"
        }
        Language::Kotlin => {
            "@Serializable\ndata class Money(\n    val amount: Double,\n    /** ISO 4217, such as JPY */\n    val currency: String,\n)\n"
        }
    }
}

fn object(language: Language, name: &str, fields: &[(String, Field)]) -> String {
    let mut out = String::new();
    match language {
        Language::TypeScript => out.push_str(&format!("export interface {name} {{\n")),
        Language::Swift => out.push_str(&format!("struct {name}: Codable, Equatable {{\n")),
        Language::Kotlin => out.push_str(&format!("@Serializable\ndata class {name}(\n")),
    }
    let indent = if language == Language::TypeScript { "  " } else { "    " };
    for (field_name, field) in fields {
        if let Some(doc) = describe(field) {
            let open = if language == Language::Swift { "///" } else { "/**" };
            let close = if language == Language::Swift { "" } else { " */" };
            out.push_str(&format!("{indent}{open} {doc}{close}\n"));
        }
        let key = identifier(language, field_name);
        let ty = type_of(language, field);
        let line = match language {
            Language::TypeScript => format!("{key}: {ty};"),
            Language::Swift => format!("var {key}: {ty}"),
            Language::Kotlin => match kotlin_default(field) {
                Some(default) => format!("val {key}: {ty} = {default},"),
                None => format!("val {key}: {ty},"),
            },
        };
        out.push_str(indent);
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str(if language == Language::Kotlin { ")\n" } else { "}\n" });
    out
}

/// What the description says of a field that its type does not: its range,
/// default, meaning, and how it is derived.
fn describe(field: &Field) -> Option<String> {
    let mut parts = Vec::new();
    if let Some(doc) = &field.doc {
        parts.push(doc.clone());
    }
    let what = if field.array {
        "count"
    } else if field.base == Base::String {
        "length"
    } else {
        "value"
    };
    match (field.lo, field.hi) {
        (Some(lo), Some(hi)) => parts.push(format!("{what} {}..{}", number(lo), number(hi))),
        (Some(lo), None) => parts.push(format!("{what} {}..", number(lo))),
        (None, Some(hi)) => parts.push(format!("{what} ..{}", number(hi))),
        (None, None) => {}
    }
    if let Some(default) = &field.default
        && !default.is_null()
    {
        parts.push(format!("default {default}"));
    }
    if let Some(derived) = &field.derived {
        parts.push(format!("derived: {derived}"));
    }
    if field.base == Base::Int && !field.array {
        parts.push("an integer".to_string());
    }
    if parts.is_empty() { None } else { Some(parts.join("; ")) }
}

fn kotlin_default(field: &Field) -> Option<String> {
    match &field.default {
        Some(serde_json::Value::Null) => Some("null".to_string()),
        Some(serde_json::Value::Bool(b)) => Some(b.to_string()),
        Some(serde_json::Value::String(s)) => Some(quoted(Language::Kotlin, s)),
        Some(serde_json::Value::Number(n)) if field.base == Base::Number => Some(decimal(n.as_f64())),
        Some(serde_json::Value::Number(n)) => Some(n.to_string()),
        _ => None,
    }
}

fn type_of(language: Language, field: &Field) -> String {
    let base = match (&field.base, language) {
        (Base::Named(name), _) => name.clone(),
        (Base::String | Base::Image | Base::Icon, Language::TypeScript) => "string".to_string(),
        (Base::String | Base::Image | Base::Icon, _) => "String".to_string(),
        (Base::Url, Language::Swift) => "URL".to_string(),
        (Base::Url, Language::TypeScript) => "string".to_string(),
        (Base::Url, Language::Kotlin) => "String".to_string(),
        (Base::Int | Base::Number, Language::TypeScript) => "number".to_string(),
        (Base::Int, _) => "Int".to_string(),
        (Base::Number, _) => "Double".to_string(),
        (Base::Bool, Language::TypeScript) => "boolean".to_string(),
        (Base::Bool, Language::Swift) => "Bool".to_string(),
        (Base::Bool, Language::Kotlin) => "Boolean".to_string(),
        (Base::Date, Language::TypeScript) => "string".to_string(),
        (Base::Date, Language::Swift) => "Date".to_string(),
        (Base::Date, Language::Kotlin) => "LocalDate".to_string(),
        (Base::Money, _) => "Money".to_string(),
    };
    let listed = match (field.array, language) {
        (false, _) => base,
        (true, Language::TypeScript) => format!("{base}[]"),
        (true, Language::Swift) => format!("[{base}]"),
        (true, Language::Kotlin) => format!("List<{base}>"),
    };
    match (field.nullable, language) {
        (false, _) => listed,
        (true, Language::TypeScript) => format!("{listed} | null"),
        (true, _) => format!("{listed}?"),
    }
}

fn enumeration(language: Language, name: &str, members: &[String]) -> String {
    match language {
        Language::TypeScript => {
            let mut quoted_members = Vec::new();
            for member in members {
                quoted_members.push(quoted(language, member));
            }
            format!("export type {name} = {};\n", quoted_members.join(" | "))
        }
        Language::Swift => {
            let mut out = format!("enum {name}: String, Codable, Equatable {{\n");
            for member in members {
                out.push_str(&format!("    case {}\n", identifier(language, member)));
            }
            out.push_str("}\n");
            out
        }
        Language::Kotlin => {
            let mut names = Vec::new();
            for member in members {
                names.push(identifier(language, member));
            }
            format!("@Serializable\nenum class {name} {{ {} }}\n", names.join(", "))
        }
    }
}

/// Each condition as a computed property of the root model (a function of
/// it in TypeScript), with its label as the comment.
fn conditions(model: &Model, language: Language, root: &str) -> String {
    let mut out = String::new();
    if language == Language::Swift {
        out.push_str(&format!("extension {root} {{\n"));
    }
    let writer = Writer { language, schema: &model.schema, model };
    let mut first = true;
    for definition in model.conditions() {
        if !first {
            out.push('\n');
        }
        first = false;
        out.push_str(&writer.condition(definition, root));
    }
    if language == Language::Swift {
        out.push_str("}\n");
    }
    out
}

/// Writes expressions in one language.
struct Writer<'a> {
    language: Language,
    schema: &'a Schema,
    model: &'a Model,
}

/// An expression as code, and whether its value may be null.
struct Code {
    text: String,
    nullable: bool,
}

impl Writer<'_> {
    fn condition(&self, definition: &Definition, root: &str) -> String {
        let name = &definition.name;
        let body = self.expr(&definition.when);
        let label = &definition.label;
        match self.language {
            Language::TypeScript => format!(
                "/** {label} */\nexport function {name}(m: {root}): boolean {{\n  return {body};\n}}\n"
            ),
            Language::Swift => format!("    /// {label}\n    var {name}: Bool {{ {body} }}\n"),
            Language::Kotlin => format!("/** {label} */\nval {root}.{name}: Boolean\n    get() = {body}\n"),
        }
    }

    fn expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::Or(items) => self.joined(items, " || ", false),
            Expr::And(items) => self.joined(items, " && ", true),
            Expr::Not(inner) => format!("!{}", self.grouped(inner)),
            Expr::Atom(atom) => {
                let code = self.atom(atom, None);
                if code.nullable { format!("{} == true", code.text) } else { code.text }
            }
            Expr::Compare(op, left, right) => self.compare(*op, left, right),
        }
    }

    fn joined(&self, items: &[Expr], separator: &str, and: bool) -> String {
        let mut parts = Vec::new();
        for item in items {
            let text = match item {
                Expr::Or(_) if and => format!("({})", self.expr(item)),
                _ => self.expr(item),
            };
            parts.push(text);
        }
        parts.join(separator)
    }

    fn grouped(&self, expr: &Expr) -> String {
        match expr {
            Expr::Atom(_) => self.expr(expr),
            _ => format!("({})", self.expr(expr)),
        }
    }

    fn compare(&self, op: Op, left: &Atom, right: &Atom) -> String {
        let (lf, rf) = (self.field_of(left), self.field_of(right));
        let l = self.atom(left, rf.as_ref());
        let r = self.atom(right, lf.as_ref());
        let symbol = op.symbol();
        if !op.orders() || !(l.nullable || r.nullable) {
            return format!("{} {symbol} {}", l.text, r.text);
        }
        // An order with a null side is false, as the description evaluates it.
        match self.language {
            Language::TypeScript => {
                let mut tests = Vec::new();
                if l.nullable {
                    tests.push(format!("{} != null", l.text));
                }
                if r.nullable {
                    tests.push(format!("{} != null", r.text));
                }
                tests.push(format!("{} {symbol} {}", l.text, r.text));
                format!("({})", tests.join(" && "))
            }
            Language::Swift => match (l.nullable, r.nullable) {
                (true, true) => {
                    format!(
                        "(({}).flatMap {{ a in ({}).map {{ b in a {symbol} b }} }} ?? false)",
                        l.text, r.text
                    )
                }
                (true, false) => format!("(({}).map {{ $0 {symbol} {} }} ?? false)", l.text, r.text),
                _ => format!("(({}).map {{ {} {symbol} $0 }} ?? false)", r.text, l.text),
            },
            Language::Kotlin => match (l.nullable, r.nullable) {
                (true, true) => {
                    format!(
                        "(({})?.let {{ a -> ({})?.let {{ b -> a {symbol} b }} }} ?: false)",
                        l.text, r.text
                    )
                }
                (true, false) => format!("(({})?.let {{ it {symbol} {} }} ?: false)", l.text, r.text),
                _ => format!("(({})?.let {{ {} {symbol} it }} ?: false)", r.text, l.text),
            },
        }
    }

    /// The field a path atom refers to, for typing the literal across from it.
    fn field_of(&self, atom: &Atom) -> Option<Field> {
        match atom {
            Atom::Name(path) if !self.is_condition(path) => {
                self.schema.resolve(&self.schema.roots(), path).map(|resolved| resolved.field)
            }
            _ => None,
        }
    }

    fn is_condition(&self, name: &str) -> bool {
        self.model.conditions.contains(name)
    }

    /// `atom` as code; `across` is the field on the other side of a
    /// comparison, which decides how a literal is written.
    fn atom(&self, atom: &Atom, across: Option<&Field>) -> Code {
        let text = match atom {
            Atom::Null => match self.language {
                Language::Swift => "nil".to_string(),
                _ => "null".to_string(),
            },
            Atom::Bool(b) => b.to_string(),
            Atom::Num(n) => match across {
                Some(field) if field.base == Base::Number => decimal(Some(*n)),
                _ => number(*n),
            },
            Atom::Str(s) => match across.and_then(|field| self.schema.members(field).map(|_| field)) {
                Some(field) => match (self.language, &field.base) {
                    (Language::Swift, _) => format!(".{}", identifier(self.language, s)),
                    (Language::Kotlin, Base::Named(name)) => {
                        format!("{name}.{}", identifier(self.language, s))
                    }
                    _ => quoted(self.language, s),
                },
                None => quoted(self.language, s),
            },
            Atom::Group(inner) => format!("({})", self.expr(inner)),
            Atom::Name(name) if self.is_condition(name) => match self.language {
                Language::TypeScript => format!("{name}(m)"),
                _ => name.clone(),
            },
            Atom::Name(path) => return self.path(path),
        };
        Code { text, nullable: false }
    }

    /// A path from the root model, with `?.` after each part that may be
    /// null; the result may be null if any part may.
    fn path(&self, path: &str) -> Code {
        let mut text = match self.language {
            Language::TypeScript => "m".to_string(),
            _ => String::new(),
        };
        let mut walked = String::new();
        let mut nullable = false;
        let roots = self.schema.roots();
        for segment in path.split('.') {
            if !text.is_empty() {
                text.push_str(if nullable { "?." } else { "." });
            }
            text.push_str(&identifier(self.language, segment));
            if !walked.is_empty() {
                walked.push('.');
            }
            walked.push_str(segment);
            if let Some(resolved) = self.schema.resolve(&roots, &walked) {
                nullable = nullable || resolved.field.nullable;
            }
        }
        Code { text, nullable }
    }
}

/// A name as an identifier: escaped where it is a keyword.
fn identifier(language: Language, name: &str) -> String {
    let keyword = match language {
        Language::TypeScript => false,
        Language::Swift => SWIFT_KEYWORDS.contains(&name),
        Language::Kotlin => KOTLIN_KEYWORDS.contains(&name),
    };
    if keyword { format!("`{name}`") } else { name.to_string() }
}

