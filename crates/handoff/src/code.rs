/// `text` as a string literal in `language`: the backslash, the quote and
/// line breaks escaped, and `$` too in Kotlin, where it starts a template.
fn quoted(language: Language, text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '$' if language == Language::Kotlin => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A number as written in a range or an integer literal: `5`, `0.5`.
fn number(n: f64) -> String {
    if n.fract() == 0.0 && n.abs() < 1e15 { format!("{}", n as i64) } else { n.to_string() }
}

/// A number as a floating-point literal: `5.0`, `0.5`.
fn decimal(n: Option<f64>) -> String {
    match n {
        Some(n) if n.fract() == 0.0 && n.abs() < 1e15 => format!("{}.0", n as i64),
        Some(n) => n.to_string(),
        None => "0.0".to_string(),
    }
}
